/* ═══ قوالب مشاريع جاهزة ═══ */
import {S,edit} from "./state.js";
import {addWall} from "./walls.js";
import {addOpen} from "./opens.js";
import {regionAt,addArea} from "./areas.js";
import {regionLoops} from "./render.js";
const T = new Map();
export function defineTemplate(t) { if (!t || !t.name) throw new Error("template: name"); T.set(t.name, t); return t; }
export const templateList = () => [...T.values()].map(t => ({ name: t.name, title: t.title || t.name }));
export const getTemplate = name => T.get(name) || null;
export function build(name) {
  const t = T.get(name); if (!t) return null;
  return typeof t.build === "function" ? t.build() : JSON.parse(JSON.stringify(t.seed || {}));
}
/* وسائط addWall لجدارٍ من بذرة — دالّةٌ خالصة يُختبَر بها التمرير
   بلا app.js: النوع الغائب int، والمحاذاة مركزية، وh للسترة. */
export const wallArgs = w => [w.a, w.b, w.th, w.type || "int", "c", w.h];
/* ═══ التطبيق — معاملةٌ واحدة، وفتحاتٌ حقيقية ═══
   كان apply() يمرّر الجدران والكتل عبر hooks خارجيةٍ (app.js)،
   وكان البابُ رمزاً زخرفياً (block:"door") يُرسَم فوق جدارٍ صلبٍ
   لم يُفتَح فعلاً: لا opens.js يعرفه، ولا BOQ يعدّه فتحةً، ولا
   الجدارُ يحمل ثقباً حقيقياً — زخرفةٌ فوق كذبة.

   والآن apply() تبني من الحالة مباشرةً بـaddWall/addOpen
   الحقيقيتَين، معاملةً واحدة عبر edit(): فبابُ القالب فتحةٌ حقيقية
   كسائر الفتحات (BOQ يعدّها، والجدارُ مثقوبٌ فعلاً)، وفشلُ أيّ
   خطوة (سماكةٌ فاسدة، فتحةٌ لا تتّسع على جدارها القصير) يُرجِع كلَّ
   شيءٍ — edit() تلتقط الاستثناء وتُعيد اللقطة، فلا تبقى جدرانٌ
   بلا فتحاتها المطلوبة. seed.opens تُنسَب بفهرس الجدار
   (wallIndex) إلى نفس ترتيب seed.walls. */
export function apply(name) {
  const seed = build(name); if (!seed) return null;
  return edit(() => {
    const walls = (seed.walls || []).map(w => addWall(...wallArgs(w)));
    const opens = (seed.opens || []).map(o => {
      const target = walls[o.wallIndex || 0];
      if (!target)
       throw new Error(`فتحة القالب: لا جدار بالفهرس ${o.wallIndex||0}`);
      return addOpen(target, o.s, o.kind || "door", o.w, o.h, o.sill,
        { hinge: o.hinge, swing: o.swing, pan: o.pan });
    });
    /* ═══ المناطق ═══ seed.areas: [{at:[x,y], name}] — نقطةٌ داخل كل فراغ
       مغلق، تُخبَز منها المنطقة بالمسار نفسه الذي تسلكه أداة «منطقة»
       (regionAt على regionLoops). لا حلقةَ عند نقطةٍ ⇒ رميٌ فتُرجَع
       الجدرانُ والفتحات كلُّها معاً: لا قالبَ نصف مُغلق. */
    const areas = [];
    if ((seed.areas || []).length) {
      const loops = regionLoops();
      (seed.areas || []).forEach(ar => {
        const ring = regionAt(loops, ar.at[0], ar.at[1]);
        if (!ring)
          throw new Error(`منطقة القالب «${ar.name || ""}»: لا حلقةَ مغلقة `
            + `عند (${ar.at[0]}، ${ar.at[1]})`);
        areas.push(addArea(ring, ar.name || "", { showArea: 1 }));
      });
    }
    if (seed.meta && seed.meta.scale) S.meta.scale = seed.meta.scale;
    return { walls, opens, areas };
  }, `تطبيق قالب ${name}`);
}
/* ═══ نوع الجدار في البيانات ═══
   كان البذرُ بلا type فتنزل كلُّ جدران القوالب «داخلية» في app.js
   قسراً — حتى محيط مبنىً قائمٍ بذاته. والآن النوعُ حقلٌ في الجدار
   (ext | int | low، وh للسترة)، والغائبُ يبقى int كما كان فقوالبُ
   المستخدم القديمة لا تتغيّر. المحيطُ خارجيّ، والقواطعُ داخلية. */
const room = (w, h, th = 150, type = "ext") => [
  { a: [0, 0], b: [w, 0], th, type }, { a: [w, 0], b: [w, h], th, type },
  { a: [w, h], b: [0, h], th, type }, { a: [0, h], b: [0, 0], th, type }
];
/* ═══ فتحات القوالب المدمجة ═══
   wallIndex يشير إلى موضع الجدار في مصفوفة walls أعلاه — الترتيب
   نفسه الذي تبنيه room()، فالجدار صفر هو الضلع السفليّ دائماً.
   s تُقاس من نقطة a للجدار المستهدَف، لا من إحداثيٍّ مطلق. */
